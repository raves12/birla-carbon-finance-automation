"""Builds docs/CLIENT_DOCUMENT_TEST_MATRIX.md from the local (git-ignored)
manifest and ground truth of the client sample pack, plus the native
extraction results once they exist (test/client_samples/results.json, written
by the sample execution run). Only non-sensitive values reach the document:
no tax registration numbers, bank accounts, IBANs, e-mails, phone numbers or
personal names.

  python scripts/client_samples/build_manifest.py
  python scripts/client_samples/build_test_matrix.py
"""
import io, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
CS = os.path.join(REPO, 'test', 'client_samples')
manifest = {r['file']: r for r in json.load(io.open(os.path.join(CS, 'manifest.json'), encoding='utf8'))}
truth = json.load(io.open(os.path.join(CS, 'ground_truth.json'), encoding='utf8'))['samples']
results_path = os.path.join(CS, 'results.json')
results = json.load(io.open(results_path, encoding='utf8')) if os.path.exists(results_path) else {}


def money(v):
    return '-' if v in (None, '') else ('{:,.2f}'.format(v) if isinstance(v, (int, float)) else str(v))


rows = []
for s in truth:
    m = manifest.get(s['file'], {})
    r = results.get(s['id'], {})
    supporting = ', '.join(s.get('supporting', [])) or '-'
    refs = []
    for k in ('po', 'grn', 'srn'):
        if s.get(k):
            refs.append(k.upper() + ' ' + str(s[k]).split(' (')[0] + (' (handwritten)' if 'HANDWRITTEN' in str(s[k]) else ''))
    expect = []
    if s.get('gross') is not None:
        expect.append('gross ' + money(s.get('gross')))
    if s.get('payment_amount') is not None:
        expect.append('paid ' + money(s.get('payment_amount')))
    if s.get('charges'):
        expect.append('charges ' + money(s['charges']))
    if s.get('tax'):
        expect.append('tax ' + money(s['tax']))
    rows.append('| ' + ' | '.join([
        s['id'], s['file'].replace('|', '/'), (m.get('sha256') or '')[:16] + '…', s['family'], s['primary'], supporting,
        str(m.get('pages', s.get('pages', '-'))), m.get('layer', s.get('layer', '-')), s.get('language', '-'),
        s.get('issuer_country') or s.get('payer_country') or '-', s.get('currency', '-'), '; '.join(expect) or '-',
        '; '.join(refs) or '-',
        r.get('native', 'NOT RUN'), r.get('critical', 'NOT RUN'), r.get('lines', 'NOT RUN'), r.get('classification', 'NOT RUN'),
        r.get('review', '-'), r.get('final', 'NOT RUN'),
        (s.get('notes') or '').replace('|', '/')[:220]]) + ' |')

head = """# CLIENT_DOCUMENT_TEST_MATRIX.md: Birla Carbon client sample pack (Phase 41)

Generated by `scripts/client_samples/build_test_matrix.py` from the local, git-ignored manifest
(`test/client_samples/manifest.json`: SHA-256, pages, text layer, scripts) and ground truth
(`test/client_samples/ground_truth.json`: fields read manually from each document).
**The documents themselves are not in source control** (`.gitignore`: `test/client_samples/`).
No tax registration numbers, bank accounts, IBANs, e-mail addresses or personal names appear here.

- **Language** = the language the document text is written in, read from the document, never from the file name or the
  parties' countries (e.g. the Bridgestone Spain / Egypt advices are English; the "Canada" Uline and Reliance packages are
  US documents in English).
- **Layer**: digital (text layer on every page), scan (no text layer), mixed (some pages scanned).
- **Native DocIntel / critical fields / lines / classification / final**: results of processing the sample with native
  ServiceNow Document Intelligence on the instance. **NOT RUN** until the sample execution run has processed it
  (`results.json`); nothing here is inferred from product documentation.

## Summary of the pack

- 28 files: 27 PDFs (11 digital, 9 scanned, 7 mixed) and one image (a file-browser screenshot, out of scope).
- Byte-identical duplicates: CS-13 = CS-14 (payment advice), CS-26 = CS-27 (vendor invoice) -> DUP-CLIENT-001 / 002.
- Same invoice in two different files (not byte-identical): CS-08 page 1 and CS-19 (Korea) -> DUP-CLIENT-003, only
  detectable at invoice level (vendor + invoice number + amount).
- Multi-document PDFs (invoice + PO + GRN / e-mails / scans): CS-07, CS-08, CS-11, CS-12, CS-16, CS-22, CS-25 (28 pages),
  CS-28 (13 pages).
- Not vendor invoices although named "Invoice": CS-17 and CS-20 are Birla Carbon's own sales invoices (seller = Birla
  Carbon Jining): AR open items. CS-23 is a PO + GRN without an invoice.
- Not a cash payment advice: CS-10 is a Chinese electronic bank acceptance draft received by endorsement (pays at
  maturity 2027-03-29). BCFA has no bank-draft / notes-receivable model: process gap, routed to review.
- Handwritten references: CS-01 (PO and service entry), CS-02 (GRN), CS-06 (GRNs), CS-27 (GRN).
- Contamination traps: CS-28 PO pages print "Sales Tax 179.70" (invoice 199.68); CS-11 PO BRL 672,238.83 vs boleto
  66,468.34; CS-12 PO BRL 36,300.00 vs NF-e 1,248.10.

## Matrix

| Sample | File | SHA-256 | AP/AR | Primary document | Supporting documents | Pages | Layer | Language | Country | Currency | Expected amounts | PO / GRN / SRN (printed) | Native DocIntel | Critical fields | Lines | Classification | Manual review | Final | Notes |
|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|
"""
summary = ''
if results:
    groups = {}
    for s in truth:
        sc = results.get(s['id'], {}).get('score')
        if not sc:
            continue
        lang = s.get('language', '-').split(' ')[0]
        kind = 'Invoice' if 'invoice' in s['primary'].lower() else 'Payment / bank advice'
        g = groups.setdefault((kind, lang), [0, 0, []])
        g[0] += sc[0]
        g[1] += sc[1]
        g[2].append(s['id'])
    finals = {}
    for v in results.values():
        k = v.get('final', '').split(' ')[0]
        finals[k] = finals.get(k, 0) + 1
    summary = ('\n## Run results (native Document Intelligence on the instance)\n\n'
               'Critical fields read correctly, compared with the ground truth (AP: vendor, invoice number, date, currency,\n'
               'net, tax, gross, PO; AR: payer, reference, amount, currency, invoice references / lines). Duplicates, '
               'expected reviews and samples not sent are not scored.\n\n'
               '| Document | Language | Samples | Critical fields correct |\n|---|---|---|---|\n' +
               '\n'.join('| %s | %s | %s | %d / %d (%d %%) |' % (k[0], k[1], ', '.join(v[2]), v[0], v[1], round(100.0 * v[0] / v[1]))
                         for k, v in sorted(groups.items())) +
               '\n\nFinal outcome per sample: ' + ', '.join('%s %d' % (k, n) for k, n in sorted(finals.items())) + '.\n')
out = head.replace('\n## Matrix\n', summary + '\n## Matrix\n') + '\n'.join(rows) + '\n'
io.open(os.path.join(REPO, 'docs', 'CLIENT_DOCUMENT_TEST_MATRIX.md'), 'w', encoding='utf8', newline='\n').write(out)
print('written', len(rows), 'rows')
