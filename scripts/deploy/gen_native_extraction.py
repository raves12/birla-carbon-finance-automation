"""Phase 40: builds scripts/deploy/phase40_native_usecases_bg.js from
native_extraction_config.json. The script creates (or updates in place) the
BCFA generative Document Intelligence use cases pinned to Now LLM: one use
case (sys_di_task_definition, capability doc_qna), one field per value
(sys_di_key, extraction type) and one extraction skill config
(di_skill_config, provider use_now_llm). Same record shapes the Document
Intelligence admin UI creates. Idempotent (fixed sys_ids).
Run the output in Scripts - Background, scope global: the field keys and skill
configs live in global scope (di_skill_config cannot be created from the app
scope), and updates of the keys from scope x_695068_bcfa fail (Phase 40 tuning 1).
Phase 42: a use case may name its own document_config (language): the CJ
model for Chinese. Usage: python scripts/deploy/gen_native_extraction.py"""
import io, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
cfg = json.load(io.open(os.path.join(HERE, 'native_extraction_config.json'), encoding='utf8'))
# A language variant ('fields_from') carries the same fields as its source use
# case: names and descriptions are taken from the source, only the key sys_ids
# are its own (Phase 42: Chinese use cases on the CJ document config).
src_by_key = {u['key']: u for u in cfg['use_cases']}
for uc in cfg['use_cases']:
    if uc.get('fields_from'):
        src = {f[1]: f for f in src_by_key[uc['fields_from']]['fields']}
        own = {f[1]: f[0] for f in uc['fields']}
        missing = [n for n in src if n not in own]
        assert not missing, (uc['key'], 'add key sys_ids for', missing)
        uc['fields'] = [[own[n], n, src[n][2], src[n][3]] for n in src]
for uc in cfg['use_cases']:
    for f in uc['fields']:
        assert len(f[2]) <= 40, f[2]  # sys_di_key.name is 40 characters
script = """// Phase 40: BCFA native extraction use cases (Document Intelligence, generative, Now LLM).
// Generated by scripts/deploy/gen_native_extraction.py from native_extraction_config.json.
// Scope global (keys and skill configs are global records). Idempotent: records are created with fixed sys_ids or updated in place.
(function() {
    var CFG = %s;
    var P = CFG.platform, out = [];
    function upsert(table, id, values) {
        var g = new GlideRecord(table);
        var exists = g.get(id);
        if (!exists) { g.initialize(); g.setNewGuidValue(id); }
        var changed = [];
        for (var k in values) {
            if (exists && k === 'name' && table === 'sys_di_key') continue; // the platform stores its own form of a key name and refuses a rename
            var cur = String(g.getValue(k)), want = String(values[k]);
            if (typeof values[k] === 'boolean') { cur = String(cur === '1' || cur === 'true'); }
            if (!exists || cur !== want) { g.setValue(k, values[k]); changed.push(k); }
        }
        if (exists && !changed.length) return '=';
        var ok = exists ? g.update() : g.insert();
        return ok ? (exists ? 'u' : 'i') : 'FAILED(' + table + ':' + changed.join('+') + ')';
    }
    CFG.use_cases.forEach(function(uc) {
        var res = [];
        res.push(upsert('sys_di_task_definition', uc.sys_id, {
            display_name: uc.name, capability: 'doc_qna', document_type: P.document_type, document_config: uc.document_config || P.document_config,
            target_table: 'x_695068_bcfa_finance_intake', active: true, state: 'current', autofill: false, stp_enabled: false,
            // Phase 42: as the Now Assist admin UI sets it. Without it the platform
            // business rule 'Update Docreader config' (sys_di_task, filter
            // task_definition.regional_hub_enabled=true) never copies the use
            // case's document config into the task, and DocReader falls back to
            // the default Latin config: the language setting is ignored.
            regional_hub_enabled: true,
            warning_threshold: 0.7, autofill_threshold: 0.01
        }));
        uc.fields.forEach(function(f, i) {
            res.push(upsert('sys_di_key', f[0], {
                task_definition: uc.sys_id, name: f[2], display_name: f[2], description: f[3], type: 'Text',
                metadata: '{"hybridFieldType":"Field","key_prediction_type":"extraction"}',
                order: i, mandatory: false, active: true, group_index: 0
            }));
        });
        res.push(upsert('di_skill_config', uc.skill_sys_id, {
            task_definition: uc.sys_id, type: 'extraction', capability: P.capability, skill_config: P.skill_config,
            flow: P.flow, config: P.skill_config_json
        }));
        var keys = new GlideAggregate('sys_di_key');
        keys.addQuery('task_definition', uc.sys_id);
        keys.addQuery('active', true);
        keys.addAggregate('COUNT');
        keys.query();
        keys.next();
        var failed = res.filter(function(r) { return r.indexOf('FAILED') === 0; });
        out.push(uc.key + ': ' + res.length + ' records (' + res.join('') .replace(/FAILED\\([^)]*\\)/g, 'F') + '), active fields=' + keys.getAggregate('COUNT') +
            (failed.length ? ', FAILED: ' + failed.join(', ') : ''));
    });
    gs.info('BCFA_NATIVEUC ' + out.join(' | '));
})();
""" % json.dumps(cfg)
dst = os.path.join(HERE, 'phase40_native_usecases_bg.js')
io.open(dst, 'w', encoding='utf8', newline='\n').write(script)
print('written', dst, len(script))
